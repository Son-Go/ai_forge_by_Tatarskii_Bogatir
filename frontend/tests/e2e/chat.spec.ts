import { expect, test } from '@playwright/test'

test('streams a recommendation, selects it, and restores history', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: /Поможем найти/ })).toBeVisible()
  await page.getByRole('button', { name: 'Подобрать решение' }).click()
  await expect(page.getByRole('textbox', { name: 'Ваше сообщение' })).toHaveValue(/50 сотрудников/)
  await page.getByRole('button', { name: 'Отправить' }).click()
  await expect(page.getByRole('button', { name: 'Выбрать', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Выбрать', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Выбрано', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('button', { name: 'Выбрано', exact: true })).toBeVisible()
  await expect(page.getByRole('article', { name: 'Вы', exact: true })).toHaveCount(1)
  await expect(page.getByRole('button', { name: 'Новый диалог', exact: true })).toBeEnabled()
  await expect(page.locator('html')).toHaveJSProperty('scrollWidth', await page.locator('html').evaluate((el) => el.clientWidth))
  await page.screenshot({ path: testInfo.outputPath('chat.png'), fullPage: true, animations: 'disabled' })
  expect(errors).toEqual([])
})

test('retries a model error without duplicating the question', async ({ page }) => {
  await page.goto('/')
  const input = page.getByRole('textbox', { name: 'Ваше сообщение' })
  await expect(page.getByRole('button', { name: 'Отправить' })).toBeDisabled()
  await input.fill('Ошибка модели')
  await expect(page.getByRole('button', { name: 'Отправить' })).toBeEnabled()
  await input.press('Enter')
  await page.getByRole('button', { name: 'Повторить отправку' }).click()
  await expect(page.getByText('Какой срок лицензии вам нужен?')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Отправить' })).toBeDisabled()
  await expect(page.getByRole('article', { name: 'Вы', exact: true })).toHaveCount(1)
})

test('recovers a broken stream and shows a missing price honestly', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: /Поможем найти/ })).toBeVisible()
  await page.getByRole('textbox').fill('Обрыв ответа, без цены')
  await page.getByRole('button', { name: 'Отправить' }).click()
  await expect(page.getByText('Цена требует уточнения', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Выбрать', exact: true })).toBeEnabled()
  await expect(page.getByRole('alert')).toHaveCount(0)
})

test('preserves the editor on HTTP rejection and recovers an interrupted reload', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: /Поможем найти/ })).toBeVisible()
  const input = page.getByRole('textbox')
  await input.fill('Лимит')
  await page.getByRole('button', { name: 'Отправить' }).click()
  await expect(input).toHaveValue('Лимит')
  await expect(page.getByRole('alert')).toContainText('Слишком много')
  await page.evaluate(() => { document.documentElement.dataset.mockSseStepped = 'true' })
  await input.fill('Подобрать решение на 50 пользователей')
  await page.getByRole('button', { name: 'Отправить' }).click()
  await expect(page.getByRole('article', { name: 'Ответ формируется' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('alert')).toContainText('прерван')
  await expect(page.getByText('Ответ прерван. Показана сохранённая часть.')).toBeVisible()
  await input.fill('Продолжим')
  await expect(page.getByRole('button', { name: 'Отправить' })).toBeEnabled()
})
