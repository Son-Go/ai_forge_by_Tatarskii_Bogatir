import { expect, test } from '@playwright/test'

test('streams a recommendation, selects it, and restores history', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: /Поможем найти/ })).toBeVisible()
  await page.getByRole('textbox', { name: 'Ваше сообщение' }).fill('Нужно защитить почту и файлы на 50 сотрудников.')
  await page.getByRole('button', { name: 'Отправить' }).click()
  await expect(page.getByRole('button', { name: 'Выбрать', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Выбрать', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Выбрано', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('button', { name: 'Выбрано', exact: true })).toBeVisible()
  await expect(page.getByRole('article', { name: 'Вы', exact: true })).toHaveCount(1)
  await expect(page.getByRole('button', { name: 'Новый диалог', exact: true })).toBeEnabled()
  await expect(page.locator('html')).toHaveJSProperty('scrollWidth', await page.locator('html').evaluate((el) => el.clientWidth))
  await page.screenshot({ path: testInfo.outputPath('chat.png'), fullPage: true, animations: 'disabled' })
  expect(errors).toEqual([])
})

test('retries a model error without duplicating the question', async ({ page }) => {
  await page.goto('/')
  const input = page.getByRole('textbox', { name: 'Ваше сообщение' })
  await expect(page.getByRole('button', { name: 'Отправить' })).toBeDisabled()
  await input.fill('Ошибка модели')
  await expect(page.getByRole('button', { name: 'Отправить' })).toBeEnabled()
  await input.press('Enter')
  await page.getByRole('button', { name: 'Повторить отправку' }).click()
  await expect(page.getByText('Какой срок лицензии вам нужен?')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Отправить' })).toBeDisabled()
  await expect(page.getByRole('article', { name: 'Вы', exact: true })).toHaveCount(1)
})

test('rotates the placeholder and resumes the three latest nonempty dialogs', async ({ page }) => {
  await page.goto('/')
  const input = page.getByRole('textbox', { name: 'Ваше сообщение' })
  const send = page.getByRole('button', { name: 'Отправить', exact: true })
  const newDialog = page.getByRole('button', { name: 'Новый диалог', exact: true })
  for (const number of [1, 2, 3, 4]) {
    await expect(newDialog).toBeEnabled()
    await expect(input).toHaveValue('')
    await expect(send).toBeDisabled()
    const example = await input.getAttribute('placeholder')
    await input.fill(`Тестовый диалог ${number}`)
    await send.click()
    await expect(page.getByRole('article', { name: 'Консультант', exact: true })).toBeVisible()
    await newDialog.click()
    await expect(input).not.toHaveAttribute('placeholder', example!)
  }
  const history = page.locator('.recent-dialogs')
  await expect(history.getByRole('button')).toHaveCount(3)
  await expect(history.getByRole('button').first()).toContainText('Тестовый диалог 4')
  await expect(history.getByRole('button', { name: /Тестовый диалог 1/ })).toHaveCount(0)
  const example = await input.getAttribute('placeholder')
  await page.reload()
  await expect(input).not.toHaveAttribute('placeholder', example!)
  await history.getByRole('button', { name: /Тестовый диалог 2/ }).click()
  await expect(page.getByRole('article', { name: 'Вы', exact: true })).toContainText('Тестовый диалог 2')
  await expect(history).toHaveCount(0)
  await page.reload()
  await expect(page.getByRole('article', { name: 'Вы', exact: true })).toContainText('Тестовый диалог 2')
  const saved = await page.evaluate(() => localStorage.getItem('softline:mock:recent'))
  expect(saved).not.toContain('Тестовый диалог')

  let newSessions = 0
  page.on('request', (request) => {
    if (request.method() === 'POST' && new URL(request.url()).pathname === '/api/v1/sessions') newSessions++
  })
  await page.getByRole('button', { name: 'На главную', exact: true }).click()
  await expect(page.getByRole('heading', { name: /Поможем найти/ })).toBeVisible()
  await expect(history.getByRole('button', { name: /Тестовый диалог 2/ })).toBeVisible()
  expect(await page.evaluate(() => localStorage.getItem('softline:mock:session'))).toBeNull()
  expect(newSessions).toBe(0)
  await input.fill('Вопрос с главной страницы')
  await send.click()
  await expect(page.getByRole('article', { name: 'Консультант', exact: true })).toBeVisible()
  await expect(page.getByRole('article', { name: 'Вы', exact: true })).toHaveText(/Вопрос с главной страницы/)
  expect(newSessions).toBe(1)
})

